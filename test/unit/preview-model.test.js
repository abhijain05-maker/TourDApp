import vm from 'node:vm'
import { describe, it, expect } from 'vitest'
import { demoSources } from '../helpers/sources.js'
import {
  buildPreviewApp,
  PreviewError,
  relativeToRoot,
  sanitizeManifest,
} from '../../srv/lib/preview/model.js'

const valid = (code) => expect(() => new vm.Script(code)).not.toThrow()
const body = (app, path) => app.files.get(path).body
const without = (sources, pattern) => sources.filter((s) => !pattern.test(s.path))

describe('buildPreviewApp (demo app)', () => {
  const app = buildPreviewApp(demoSources())

  it('contains views, fragments, i18n and the generated files, relative to the app root', () => {
    expect([...app.files.keys()].sort()).toEqual([
      'Component.js',
      'controller/App.controller.js',
      'controller/Detail.controller.js',
      'controller/Main.controller.js',
      'fragment/ConfirmDialog.fragment.xml',
      'i18n/i18n.properties',
      'i18n/i18n_en.properties',
      'manifest.json',
      'view/App.view.xml',
      'view/Detail.view.xml',
      'view/Main.view.xml',
    ])
    expect(body(app, 'view/Main.view.xml')).toContain('id="createBtn"')
  })

  it('reports what the copy contains', () => {
    expect(app.info).toMatchObject({
      appId: 'demo.orders',
      controllers: 'stub',
      stubbedControllers: 3,
      rootView: 'demo.orders.view.App',
      mockModels: [''],
    })
    expect(app.info.routes).toEqual([
      { name: 'main', pattern: '', params: [] },
      { name: 'detail', pattern: 'order/{orderId}', params: ['orderId'] },
    ])
  })

  it('removes everything from the manifest that needs a backend and keeps routing and i18n', () => {
    const m = JSON.parse(body(app, 'manifest.json'))
    expect(m['sap.app'].dataSources).toBeUndefined()
    expect(m['sap.ui5'].resourceRoots).toBeUndefined()
    expect(m['sap.ui5'].flexEnabled).toBe(false)
    expect(m['sap.ui5'].models['']).toEqual({ type: 'sap.ui.model.json.JSONModel' })
    expect(m['sap.ui5'].models.i18n.settings.bundleName).toBe('demo.orders.i18n.i18n')
    expect(m['sap.ui5'].routing.routes).toHaveLength(2)
    expect(m['sap.ui5'].rootView.viewName).toBe('demo.orders.view.App')
  })

  it('generates a component that starts the router and fills the sample data', () => {
    const code = body(app, 'Component.js')
    valid(code)
    expect(code).toContain('"demo.orders.Component"')
    expect(code).toContain('"Orders"')
    expect(code).toContain('router.initialize()')
  })

  it('generates stub controllers: handlers that move between pages and open dialogs, no uploaded code', () => {
    const main = body(app, 'controller/Main.controller.js')
    valid(main)
    expect(main).toContain('generated by TourD')
    expect(main).not.toContain('MessageToast')
    expect(main).toContain('"onCreate":{"navTo":{"route":"detail","params":{"orderId":"new"}}}')
    expect(main).toContain('"onItemPress":{"navTo":{"route":"detail","params":{"orderId":"1"}}}')
    expect(main).toContain('"onExport":{}')
    const detail = body(app, 'controller/Detail.controller.js')
    valid(detail)
    expect(detail).toContain('ConfirmDialog')
  })

  it('uses the uploaded controllers in "real" mode', () => {
    const real = buildPreviewApp(demoSources(), { controllers: 'real' })
    expect(body(real, 'controller/Main.controller.js')).toContain('MessageToast')
    expect(real.info.controllers).toBe('real')
    expect(real.info.stubbedControllers).toBe(0)
  })
})

describe('buildPreviewApp (edge cases)', () => {
  it('needs a manifest and says so', () => {
    expect(() => buildPreviewApp(without(demoSources(), /manifest\.json$/))).toThrow(PreviewError)
    expect(() => buildPreviewApp(without(demoSources(), /manifest\.json$/))).toThrow(
      /manifest\.json/,
    )
  })

  it('rejects a manifest that is not JSON or has no app id', () => {
    const swap = (content) =>
      demoSources().map((s) => (s.path.endsWith('webapp/manifest.json') ? { ...s, content } : s))
    expect(() => buildPreviewApp(swap('{ nope'))).toThrow(/not valid JSON/)
    expect(() => buildPreviewApp(swap('{"sap.app":{}}'))).toThrow(/app id/)
  })

  it('still stubs a controller whose file was not uploaded', () => {
    const app = buildPreviewApp(without(demoSources(), /Main\.controller\.js$/))
    const main = body(app, 'controller/Main.controller.js')
    valid(main)
    expect(main).toContain('"onCreate":{}') // no source, so no navigation to copy
  })

  it('leaves out controllers that are outside the app namespace', () => {
    const sources = demoSources().map((s) =>
      s.path.endsWith('Main.view.xml')
        ? { ...s, content: s.content.replace('demo.orders.controller.Main', 'other.lib.Main') }
        : s,
    )
    const app = buildPreviewApp(sources)
    expect(app.info.notes.join()).toContain('other.lib.Main')
  })

  it('uses a stub for TypeScript controllers even in real mode', () => {
    const sources = demoSources().map((s) =>
      s.path.endsWith('Main.controller.js') ? { ...s, path: s.path.replace('.js', '.ts') } : s,
    )
    const app = buildPreviewApp(sources, { controllers: 'real' })
    expect(body(app, 'controller/Main.controller.js')).toContain('generated by TourD')
    expect(app.info.notes.join()).toContain('TypeScript')
  })

  it('works when the files are not under webapp/', () => {
    const sources = demoSources().map((s) => ({ ...s, path: s.path.replace(/^webapp\//, 'src/') }))
    expect(buildPreviewApp(sources).files.has('view/Main.view.xml')).toBe(true)
  })

  it('keeps hostile names from breaking out of the generated code', () => {
    const sources = demoSources().map((s) =>
      s.path.endsWith('Main.view.xml')
        ? { ...s, content: s.content.replace('.onCreate', '.onX</script><script>alert(1)') }
        : s,
    )
    for (const [path, f] of buildPreviewApp(sources).files)
      if (path.endsWith('.js')) expect(f.body).not.toContain('</script>')
  })
})

describe('helpers', () => {
  it('relativeToRoot', () => {
    expect(relativeToRoot('webapp/view/A.view.xml', 'webapp/')).toBe('view/A.view.xml')
    expect(relativeToRoot('x/webapp/view/A.view.xml', '')).toBe('view/A.view.xml')
    expect(relativeToRoot('view\\A.view.xml', '')).toBe('view/A.view.xml')
  })

  it('sanitizeManifest turns OData and unknown models into JSON models and adds mocked ones', () => {
    const m = sanitizeManifest(
      {
        'sap.app': { id: 'a.b', dataSources: { x: {} } },
        'sap.ui5': {
          models: {
            '': { dataSource: 'x', type: 'sap.ui.model.odata.v4.ODataModel' },
            i18n: {
              type: 'sap.ui.model.resource.ResourceModel',
              settings: { bundleName: 'a.b.i18n.i18n' },
            },
          },
          dependencies: { libs: { 'sap.m': {} }, components: { other: {} } },
          componentUsages: { u: {} },
        },
      },
      ['', 'shop'],
    )
    expect(m['sap.ui5'].models).toEqual({
      '': { type: 'sap.ui.model.json.JSONModel' },
      i18n: {
        type: 'sap.ui.model.resource.ResourceModel',
        settings: { bundleName: 'a.b.i18n.i18n' },
      },
      shop: { type: 'sap.ui.model.json.JSONModel' },
    })
    expect(m['sap.ui5'].dependencies.components).toBeUndefined()
    expect(m['sap.ui5'].componentUsages).toBeUndefined()
    expect(m['sap.app'].dataSources).toBeUndefined()
  })
})
