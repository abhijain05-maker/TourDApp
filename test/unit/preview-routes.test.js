import cds from '@sap/cds'
import { describe, it, expect, beforeAll } from 'vitest'
import { demoSources } from '../helpers/sources.js'

const { GET, POST, axios } = cds.test(import.meta.dirname + '/../..')
const BASE = '/odata/v4/tour'

// plain HTTP, whatever the status
const raw = (path, config = {}) => axios.get(path, { validateStatus: () => true, ...config })

describe('sandbox preview routes', () => {
  let projectID
  beforeAll(async () => {
    projectID = (await POST(`${BASE}/Projects`, { name: 'Preview' })).data.ID
    await POST(`${BASE}/importSources`, { projectID, files: demoSources(), replace: true })
  })

  it('serves the sandbox page with the app configuration, framed without same-origin access', async () => {
    const r = await raw(
      `/preview/${projectID}/sandbox.html?ui5=1.148&parentOrigin=http://localhost:5173`,
    )
    expect(r.status).toBe(200)
    expect(r.headers['content-type']).toMatch(/text\/html/)
    expect(r.headers['content-security-policy']).toBe(
      "sandbox allow-scripts; frame-ancestors 'self'",
    )
    expect(r.headers['access-control-allow-origin']).toBe('*')
    const config = JSON.parse(/window\.__TOURD__ = (\{.*\});/.exec(r.data)[1])
    expect(config).toEqual({
      appId: 'demo.orders',
      appBase: './app/',
      ui5: '1.148',
      parentOrigin: 'http://localhost:5173',
    })
  })

  it('ignores a UI5 version or parent origin that does not look right', async () => {
    const r = await raw(
      `/preview/${projectID}/sandbox.html?ui5=../../x&parentOrigin=javascript:alert(1)`,
    )
    const config = JSON.parse(/window\.__TOURD__ = (\{.*\});/.exec(r.data)[1])
    expect(config.ui5).toBe('1.120')
    expect(config.parentOrigin).toBe('*')
  })

  it('selects uploaded controllers only when asked', async () => {
    const r = await raw(`/preview/${projectID}/sandbox.html?controllers=real`)
    expect(JSON.parse(/window\.__TOURD__ = (\{.*\});/.exec(r.data)[1]).appBase).toBe('./app-real/')
    const stub = await raw(`/preview/${projectID}/app/controller/Main.controller.js`)
    expect(stub.data).toContain('generated by TourD')
    const real = await raw(`/preview/${projectID}/app-real/controller/Main.controller.js`)
    expect(real.data).toContain('MessageToast')
    expect(real.data).not.toContain('generated by TourD')
  })

  it('serves the files of the app with the right types and CORS', async () => {
    for (const [path, type] of [
      ['view/Main.view.xml', /xml/],
      ['fragment/ConfirmDialog.fragment.xml', /xml/],
      ['i18n/i18n.properties', /text\/plain/],
      ['manifest.json', /json/],
      ['Component.js', /javascript/],
    ]) {
      const r = await raw(`/preview/${projectID}/app/${path}`)
      expect(r.status, path).toBe(200)
      expect(r.headers['content-type'], path).toMatch(type)
      expect(r.headers['access-control-allow-origin']).toBe('*')
      expect(r.headers['x-content-type-options']).toBe('nosniff')
    }
  })

  it('serves the runtime files (player and sandbox) but nothing else from the repository', async () => {
    expect((await raw(`/preview/${projectID}/rt/TourPlayer.js`)).data).toContain('sap.ui.define')
    expect((await raw(`/preview/${projectID}/rt/sandbox.js`)).data).toContain('tourd/sandbox')
    for (const p of [
      'rt/../package.json',
      'rt/package.json',
      'rt/..%2Fpackage.json',
      'rt/db.sqlite',
    ])
      expect((await raw(`/preview/${projectID}/${p}`)).status, p).toBe(404)
  })

  it('rejects traversal and files that are not part of the app', async () => {
    for (const p of [
      'app/..%2F..%2Fpackage.json',
      'app/%2e%2e/package.json',
      'app/view/..%5C..%5Cx',
      'app/%00',
      'app/nope.js',
    ])
      expect([400, 404], p).toContain((await raw(`/preview/${projectID}/${p}`)).status)
    expect((await raw(`/preview/${projectID}/app/package.json`)).status).toBe(404) // uploaded, but not an app file
  })

  it('answers 404 for unknown or malformed project ids and 405 for writes', async () => {
    expect(
      (await raw(`/preview/${'0'.repeat(8)}-0000-0000-0000-${'0'.repeat(12)}/sandbox.html`)).status,
    ).toBe(404)
    expect((await raw(`/preview/not-an-id/sandbox.html`)).status).toBe(404)
    const r = await axios.post(
      `/preview/${projectID}/sandbox.html`,
      {},
      { validateStatus: () => true },
    )
    expect(r.status).toBe(405)
  })

  it('explains what is missing when the app cannot be built', async () => {
    const empty = (await POST(`${BASE}/Projects`, { name: 'Empty' })).data.ID
    const page = await raw(`/preview/${empty}/sandbox.html`)
    expect(page.status).toBe(422)
    expect(page.data).toContain('manifest.json')
    expect(page.headers['content-security-policy']).toBe(
      "sandbox allow-scripts; frame-ancestors 'self'",
    )
    const info = await raw(`/preview/${empty}/info.json`)
    expect(info.status).toBe(422)
    expect(info.data.error).toContain('manifest.json')
  })

  it('refreshes the copy when the files change', async () => {
    const id = (await POST(`${BASE}/Projects`, { name: 'Changing' })).data.ID
    await POST(`${BASE}/importSources`, { projectID: id, files: demoSources(), replace: true })
    const before = (await raw(`/preview/${id}/app/view/Main.view.xml`)).data
    const files = demoSources().map((f) =>
      f.path.endsWith('Main.view.xml')
        ? { ...f, content: f.content.replace('Create', 'Brand new') }
        : f,
    )
    await POST(`${BASE}/importSources`, { projectID: id, files, replace: true })
    expect((await raw(`/preview/${id}/app/view/Main.view.xml`)).data).not.toBe(before)
  })

  it('describes the app in info.json', async () => {
    const { data } = await GET(`/preview/${projectID}/info.json`)
    expect(data).toMatchObject({
      appId: 'demo.orders',
      controllers: 'stub',
      rootView: 'demo.orders.view.App',
    })
    expect(data.routes.map((r) => r.name)).toEqual(['main', 'detail'])
  })
})

describe('live routes', () => {
  it('serves the player under an explicit module name, for a plain <script>', async () => {
    const r = await raw('/live/player.js')
    expect(r.status).toBe(200)
    expect(r.headers['access-control-allow-origin']).toBe('*')
    expect(r.data).toContain('sap.ui.predefine("tourd/live/TourPlayer", ')
    expect(r.data).not.toMatch(/sap\.ui\.define\(/)
  })

  it('serves the recorder as a console snippet that starts without the bridge', async () => {
    const r = await raw('/live/recorder.js')
    expect(r.status).toBe(200)
    expect(r.headers['content-type']).toContain('javascript')
    expect(r.data).toContain('window.__tourdRecorder')
    expect(r.data).toContain('recorder.start({ bridge: false })')
  })

  it('serves the saved tour of a known id only', async () => {
    const projectID = (await POST(`${BASE}/Projects`, { name: 'Live' })).data.ID
    const definition = {
      schemaVersion: 1,
      id: 'mine',
      title: 'Mine',
      steps: [{ id: 's1', title: 'Hello' }],
    }
    const tour = (
      await POST(`${BASE}/createTour`, {
        projectID,
        name: 'Mine',
        definition: JSON.stringify(definition),
      })
    ).data
    const r = await raw(`/live/${tour.ID}/tour.json`)
    expect(r.status).toBe(200)
    expect(r.headers['access-control-allow-origin']).toBe('*')
    expect(r.data.steps[0].title).toBe('Hello')
    expect(
      (await raw(`/live/${'0'.repeat(8)}-0000-0000-0000-${'0'.repeat(12)}/tour.json`)).status,
    ).toBe(404)
    expect((await raw('/live/x/tour.json')).status).toBe(404)
    expect((await raw('/live/other.js')).status).toBe(404)
  })
})
