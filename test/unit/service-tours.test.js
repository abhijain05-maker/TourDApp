import cds from '@sap/cds'
import { describe, it, expect, beforeAll } from 'vitest'
import { readFileSync } from 'node:fs'
import { demoSources } from '../helpers/sources.js'

const { GET, POST, PATCH, DELETE } = cds.test(import.meta.dirname + '/../..')
const BASE = '/odata/v4/tour'
const fx = (n) => readFileSync(`test/fixtures/recordings/demo-create-order.${n}`, 'utf8')
const UNKNOWN = '00000000-0000-0000-0000-000000000000'

const fails = (p) =>
  p.then(
    (r) => ({ status: r.status, message: 'unexpected success' }),
    (e) => ({
      status: e.response?.status ?? e.code,
      message: e.response?.data?.error?.message ?? e.message,
    }),
  )

async function waitFor(jobID) {
  for (let i = 0; i < 100; i++) {
    const { data } = await GET(`${BASE}/GenerationJobs(${jobID})`)
    if (data.status === 'done' || data.status === 'failed') return data
    await new Promise((r) => setTimeout(r, 50))
  }
  throw new Error('job did not finish')
}

async function setup() {
  const projectID = (await POST(`${BASE}/Projects`, { name: 'Tours' })).data.ID
  await POST(`${BASE}/importSources`, { projectID, files: demoSources(), replace: true })
  const recordingID = (
    await POST(`${BASE}/importRecording`, { projectID, raw: fx('devtools.json') })
  ).data.ID
  const job = await waitFor(
    (await POST(`${BASE}/generateTour`, { projectID, recordingID })).data.ID,
  )
  const tour = (await GET(`${BASE}/Tours(${job.tour_ID})`)).data
  return { projectID, recordingID, tourID: tour.ID, definition: JSON.parse(tour.definition) }
}

const versionsOf = async (tourID) =>
  (await GET(`${BASE}/TourVersions?$filter=tour_ID eq ${tourID}&$orderby=version`)).data.value.map(
    (v) => v.version,
  )
const definitionOf = async (tourID) =>
  JSON.parse((await GET(`${BASE}/Tours(${tourID})`)).data.definition)

describe('saving and versioning', () => {
  let ctx
  beforeAll(async () => {
    ctx = await setup()
  })

  it('saveTour appends a version and returns the tour', async () => {
    const def = structuredClone(ctx.definition)
    def.steps[1].title = 'Find an order'
    const { data } = await POST(`${BASE}/saveTour`, {
      tourID: ctx.tourID,
      definition: JSON.stringify(def),
      note: 'Reworded',
    })
    expect(data).toMatchObject({ ID: ctx.tourID, version: 2 })
    expect((await definitionOf(ctx.tourID)).steps[1].title).toBe('Find an order')
    const versions = (
      await GET(`${BASE}/TourVersions?$filter=tour_ID eq ${ctx.tourID}&$orderby=version`)
    ).data.value
    expect(versions.map((v) => [v.version, v.note])).toEqual([
      [1, 'Generated by rules'],
      [2, 'Reworded'],
    ])
  })

  it('saving an unchanged definition does not create a version', async () => {
    const current = await definitionOf(ctx.tourID)
    const { data } = await POST(`${BASE}/saveTour`, {
      tourID: ctx.tourID,
      definition: JSON.stringify(current),
    })
    expect(data.version).toBe(2)
    expect(await versionsOf(ctx.tourID)).toEqual([1, 2])
  })

  it('applies schema defaults when saving a minimal document', async () => {
    const def = { schemaVersion: 1, id: 'min', title: 'Minimal', steps: [{ id: 'a', title: 'A' }] }
    const { data } = await POST(`${BASE}/saveTour`, {
      tourID: ctx.tourID,
      definition: JSON.stringify(def),
    })
    const stored = JSON.parse(data.definition)
    expect(stored.options).toEqual({
      showProgress: true,
      allowSkip: true,
      overlay: true,
      interactive: true,
      waitTimeoutMs: 5000,
    })
    expect(stored.steps[0]).toMatchObject({
      text: '',
      placement: 'PreferredBottomOrFlip',
      before: [],
    })
    expect(data.version).toBe(3)
  })

  it('restoreVersion re-saves an old definition as a new version', async () => {
    const v1 = JSON.parse(
      (await GET(`${BASE}/getTourVersion(tourID=${ctx.tourID},version=1)`)).data.value,
    )
    expect(v1.steps).toHaveLength(7)
    const { data } = await POST(`${BASE}/restoreVersion`, { tourID: ctx.tourID, version: 1 })
    expect(data.version).toBe(4)
    expect(JSON.parse(data.definition)).toEqual(v1)
    const last = (
      await GET(`${BASE}/TourVersions?$filter=tour_ID eq ${ctx.tourID} and version eq 4`)
    ).data.value[0]
    expect(last.note).toBe('Restored version 1')
  })

  it('rejects invalid documents with a helpful message and keeps the tour unchanged', async () => {
    const before = await versionsOf(ctx.tourID)
    const def = structuredClone(ctx.definition)
    def.steps[0].placment = 'Top'
    def.steps[2].placement = 'Sideways'
    const r = await fails(
      POST(`${BASE}/saveTour`, { tourID: ctx.tourID, definition: JSON.stringify(def) }),
    )
    expect(r.status).toBe(400)
    expect(r.message).toContain('steps[2].placement')
    expect(
      await fails(POST(`${BASE}/saveTour`, { tourID: ctx.tourID, definition: '{ nope' })),
    ).toMatchObject({ status: 400, message: expect.stringContaining('not valid JSON') })
    expect(await versionsOf(ctx.tourID)).toEqual(before)
  })

  it('returns 404 for unknown tours and versions', async () => {
    expect(
      (await fails(POST(`${BASE}/saveTour`, { tourID: UNKNOWN, definition: '{}' }))).status,
    ).toBe(404)
    expect(
      (await fails(POST(`${BASE}/restoreVersion`, { tourID: ctx.tourID, version: 99 }))).status,
    ).toBe(404)
    expect(
      (await fails(GET(`${BASE}/getTourVersion(tourID=${ctx.tourID},version=99)`))).status,
    ).toBe(404)
    expect((await fails(GET(`${BASE}/lintTour(tourID=${UNKNOWN})`))).status).toBe(404)
  })
})

describe('autosave and concurrent edits', () => {
  let ctx
  beforeAll(async () => {
    ctx = await setup()
  })
  const titled = (title) => JSON.stringify({ ...ctx.definition, title })
  const save = (body) => POST(`${BASE}/saveTour`, { tourID: ctx.tourID, ...body })
  const notes = async () =>
    (
      await GET(`${BASE}/TourVersions?$filter=tour_ID eq ${ctx.tourID}&$orderby=version`)
    ).data.value.map((v) => [v.version, v.note])

  it('coalesces consecutive autosaves into one version', async () => {
    await save({ definition: titled('A'), autosave: true })
    await save({ definition: titled('AB'), autosave: true })
    const { data } = await save({ definition: titled('ABC'), autosave: true })
    expect(data.version).toBe(2)
    expect(JSON.parse(data.definition).title).toBe('ABC')
    expect(await notes()).toEqual([
      [1, 'Generated by rules'],
      [2, 'Autosave'],
    ])
    const v2 = JSON.parse(
      (await GET(`${BASE}/getTourVersion(tourID=${ctx.tourID},version=2)`)).data.value,
    )
    expect(v2.title).toBe('ABC')
  })

  it('an explicit save is a version of its own, and the next autosave starts a new one after it', async () => {
    const { data } = await save({ definition: titled('Reviewed'), note: 'Reviewed with Anna' })
    expect(data.version).toBe(3)
    await save({ definition: titled('Reviewed 2'), autosave: true })
    await save({ definition: titled('Reviewed 3'), autosave: true })
    expect(await notes()).toEqual([
      [1, 'Generated by rules'],
      [2, 'Autosave'],
      [3, 'Reviewed with Anna'],
      [4, 'Autosave'],
    ])
  })

  it('naming the stored state labels the latest version instead of ignoring the request', async () => {
    const ctx2 = await setup()
    const post = (body) => POST(`${BASE}/saveTour`, { tourID: ctx2.tourID, ...body })
    const def = JSON.stringify({ ...ctx2.definition, title: 'Draft' })
    await post({ definition: def, autosave: true }) // v2 "Autosave"
    const labelled = await post({ definition: def, note: 'Reviewed with Anna' })
    expect(labelled.data.version).toBe(2) // same content: the autosave version is renamed
    const rows = async () =>
      (
        await GET(`${BASE}/TourVersions?$filter=tour_ID eq ${ctx2.tourID}&$orderby=version`)
      ).data.value.map((v) => [v.version, v.note])
    expect(await rows()).toEqual([
      [1, 'Generated by rules'],
      [2, 'Reviewed with Anna'],
    ])

    // naming again without a change keeps both names as separate snapshots
    const again = await post({ definition: def, note: 'Approved by legal' })
    expect(again.data.version).toBe(3)
    expect(await rows()).toEqual([
      [1, 'Generated by rules'],
      [2, 'Reviewed with Anna'],
      [3, 'Approved by legal'],
    ])
    // and an unchanged autosave or restore stays a no-op
    expect((await post({ definition: def, autosave: true })).data.version).toBe(3)
  })

  it('rejects a save based on an outdated version instead of overwriting newer work', async () => {
    const current = (await GET(`${BASE}/Tours(${ctx.tourID})`)).data.version
    const r = await fails(save({ definition: titled('Stale'), baseVersion: current - 1 }))
    expect(r).toMatchObject({ status: 409, message: expect.stringContaining('changed elsewhere') })
    expect(JSON.parse((await GET(`${BASE}/Tours(${ctx.tourID})`)).data.definition).title).not.toBe(
      'Stale',
    )
    expect(
      (await save({ definition: titled('Fresh'), baseVersion: current, autosave: true })).status,
    ).toBe(200)
  })
})

describe('creating and editing directly', () => {
  let ctx
  beforeAll(async () => {
    ctx = await setup()
  })

  it('createTour stores a manual tour with version 1', async () => {
    const def = {
      schemaVersion: 1,
      id: 'hand',
      title: 'By hand',
      steps: [
        {
          id: 's1',
          title: 'Hello',
          target: { viewName: 'demo.orders.view.Main', controlId: 'createBtn' },
        },
      ],
    }
    const { data } = await POST(`${BASE}/createTour`, {
      projectID: ctx.projectID,
      name: 'Hand made',
      definition: JSON.stringify(def),
    })
    expect(data).toMatchObject({ name: 'Hand made', generator: 'manual', version: 1 })
    expect(await versionsOf(data.ID)).toEqual([1])
    expect(
      (
        await fails(
          POST(`${BASE}/createTour`, {
            projectID: ctx.projectID,
            name: 'x',
            definition: '{"steps":[]}',
          }),
        )
      ).status,
    ).toBe(400)
  })

  it('allows renaming but not editing the definition directly', async () => {
    await PATCH(`${BASE}/Tours(${ctx.tourID})`, { name: 'Renamed' })
    expect((await GET(`${BASE}/Tours(${ctx.tourID})`)).data.name).toBe('Renamed')
    expect(await fails(PATCH(`${BASE}/Tours(${ctx.tourID})`, { definition: '{}' }))).toMatchObject({
      status: 400,
      message: expect.stringContaining('saveTour'),
    })
    expect(await fails(PATCH(`${BASE}/Tours(${ctx.tourID})`, { version: 9 }))).toMatchObject({
      status: 400,
    })
  })

  it('lint reflects saved edits', async () => {
    const def = structuredClone(ctx.definition)
    def.steps[1].target.controlId = 'ghost'
    await POST(`${BASE}/saveTour`, { tourID: ctx.tourID, definition: JSON.stringify(def) })
    const { data } = await GET(`${BASE}/lintTour(tourID=${ctx.tourID})`)
    expect(data.errors).toBe(1)
    expect(data.issues[0]).toMatchObject({
      code: 'target.notFound',
      severity: 'error',
      stepId: 's1',
    })
  })
})

describe('deleting', () => {
  it('deleting a tour removes its versions; deleting a project removes everything', async () => {
    const ctx = await setup()
    const count = async (entity, filter) =>
      (await GET(`${BASE}/${entity}?$filter=${filter}&$count=true&$top=0`)).data['@odata.count']
    expect(await count('TourVersions', `tour_ID eq ${ctx.tourID}`)).toBe(1)

    await DELETE(`${BASE}/Tours(${ctx.tourID})`)
    expect(await count('TourVersions', `tour_ID eq ${ctx.tourID}`)).toBe(0)

    const second = await setup()
    await DELETE(`${BASE}/Projects(${second.projectID})`)
    const byProject = `project_ID eq ${second.projectID}`
    for (const entity of ['Sources', 'Recordings', 'Tours', 'GenerationJobs']) {
      expect(await count(entity, byProject), entity).toBe(0)
    }
    expect(await count('TourVersions', `tour_ID eq ${second.tourID}`)).toBe(0)
  })
})
