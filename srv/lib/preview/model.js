// Turns a project's uploaded sources into a runnable, harmless copy of the app for the sandbox preview.
//
// What is served:  views, fragments and i18n bundles exactly as uploaded;
//                  a manifest.json without anything that needs a backend (data sources, OData models, ...);
//                  a generated Component.js (router start + sample data);
//                  controllers: generated stubs (default) or the uploaded code ("real" mode).
// Uploaded controller code is never run unless the user asks for it, and then only inside the
// sandboxed iframe (no access to TourD).
import { buildInventory, classifySource, pickManifest } from '../context/inventory.js'
import { parseManifest } from '../parsers/manifest.js'
import { parseXmlView } from '../parsers/xml-view.js'
import { jsonForScript as jsString } from '../../../shared/live-snippet.mjs'
import { inferMockData } from './mock.js'

export class PreviewError extends Error {}

const norm = (p) => p.replace(/\\/g, '/')
const dirOf = (p) => p.slice(0, Math.max(0, p.lastIndexOf('/') + 1))

const TYPES = {
  xml: 'application/xml; charset=utf-8',
  js: 'application/javascript; charset=utf-8',
  json: 'application/json; charset=utf-8',
  properties: 'text/plain; charset=utf-8',
}

/** Path of a source relative to the app root (the folder of manifest.json). */
export function relativeToRoot(path, rootDir) {
  const p = norm(path)
  if (rootDir && p.startsWith(rootDir)) return p.slice(rootDir.length)
  if (p.includes('webapp/')) return p.slice(p.lastIndexOf('webapp/') + 'webapp/'.length)
  return p
}

const DEFAULT_ID = /^[A-Za-z_$][\w$]*$/

/** The manifest without anything that would call a backend or load code we do not serve. */
export function sanitizeManifest(manifest, mockModels) {
  const m = structuredClone(manifest)
  const app = (m['sap.app'] ??= {})
  const ui5 = (m['sap.ui5'] ??= {})
  delete app.dataSources
  delete app.crossNavigation
  delete m['sap.cloud']
  delete m['sap.platform.abap']
  delete m['sap.platform.hcp']
  delete m['sap.fiori']
  delete ui5.resourceRoots
  delete ui5.componentUsages
  delete ui5.extends
  delete ui5.services
  if (ui5.dependencies) delete ui5.dependencies.components
  ui5.flexEnabled = false

  const models = {}
  for (const [name, cfg] of Object.entries(ui5.models ?? {})) {
    models[name] =
      cfg?.type === 'sap.ui.model.resource.ResourceModel'
        ? cfg
        : { type: 'sap.ui.model.json.JSONModel' }
  }
  for (const name of mockModels) models[name] ??= { type: 'sap.ui.model.json.JSONModel' }
  ui5.models = models
  return m
}

function componentSource(appId, mock) {
  return `sap.ui.define(["sap/ui/core/UIComponent"], function (UIComponent) {
	"use strict";
	// generated by TourD for the sandbox preview - not the app's own Component.js
	var MOCK = ${jsString(mock)};
	return UIComponent.extend(${jsString(appId + '.Component')}, {
		metadata: { manifest: "json", interfaces: ["sap.ui.core.IAsyncContentCreation"] },
		init: function () {
			UIComponent.prototype.init.apply(this, arguments);
			Object.keys(MOCK).forEach(function (name) {
				var model = this.getModel(name || undefined);
				if (model && model.setData) {
					model.setData(MOCK[name]);
				}
			}, this);
			var router = this.getRouter();
			if (router) {
				router.initialize();
			}
		}
	});
});
`
}

function stubSource(controllerName, actions) {
  return `sap.ui.define(["sap/ui/core/mvc/Controller", "sap/ui/core/Fragment"], function (Controller, Fragment) {
	"use strict";
	// generated by TourD for the sandbox preview: handlers do nothing, except moving between pages
	// and opening dialogs where the real controller does so
	var ACTIONS = ${jsString(actions)};
	function open(controller, action) {
		var cache = (controller._tourdDialogs = controller._tourdDialogs || {});
		var loaded = cache[action.name] || (cache[action.name] = Fragment.load({
			id: action.id === "view" ? controller.getView().getId() : action.id || undefined,
			name: action.name,
			controller: controller
		}).then(function (dialog) {
			controller.getView().addDependent(dialog);
			return dialog;
		}));
		return loaded.then(function (dialog) {
			controller._tourdOpen = dialog;
			if (dialog.open) {
				dialog.open();
			}
		});
	}
	var Stub = Controller.extend(${jsString(controllerName)}, {});
	Object.keys(ACTIONS).forEach(function (name) {
		Stub.prototype[name] = function () {
			var action = ACTIONS[name];
			try {
				if (action.navTo) {
					this.getOwnerComponent().getRouter().navTo(action.navTo.route, action.navTo.params);
				} else if (action.fragment) {
					open(this, action.fragment);
				} else if (action.close && this._tourdOpen && this._tourdOpen.close) {
					this._tourdOpen.close();
				}
			} catch (e) {
				console.warn("[TourD sandbox] handler " + name + " failed", e);
			}
		};
	});
	return Stub;
});
`
}

const CLOSING = /close|cancel|dismiss|confirm|^onok$|^onyes$|^onno$/i

/**
 * @param {Array<{path: string, kind?: string, content: string}>} sources
 * @param {{appId?: string, controllers?: 'stub'|'real'}} [options]
 * @returns {{appId: string, files: Map<string, {type: string, body: string}>, info: object}}
 */
export function buildPreviewApp(sources, options = {}) {
  const mode = options.controllers === 'real' ? 'real' : 'stub'
  const manifestSrc = pickManifest(sources.filter((s) => classifySource(s.path) === 'manifest'))
  if (!manifestSrc)
    throw new PreviewError(
      "The sandbox needs the app's manifest.json. Add it to the project's files and try again.",
    )
  let manifestJson
  try {
    manifestJson = JSON.parse(manifestSrc.content)
  } catch (e) {
    throw new PreviewError(`manifest.json is not valid JSON: ${e.message}`)
  }
  const manifest = parseManifest(manifestJson)
  const appId = manifest.appId ?? options.appId
  if (!appId || !DEFAULT_ID.test(appId.split('.')[0]))
    throw new PreviewError('The sandbox needs the app id ("sap.app" > "id") in manifest.json.')
  const rootDir = dirOf(norm(manifestSrc.path))
  const rel = (path) => relativeToRoot(path, rootDir)
  const inventory = buildInventory(sources, { namespace: appId })

  const files = new Map()
  const put = (path, type, body) => files.set(path, { type: TYPES[type], body })
  const notes = []

  // views, fragments, i18n: as uploaded
  for (const s of sources) {
    const kind = classifySource(s.path)
    if (kind === 'view' || kind === 'fragment') put(rel(s.path), 'xml', s.content)
    else if (kind === 'i18n') put(rel(s.path), 'properties', s.content)
  }

  // sample data for every model the views bind to
  const resourceModels = new Set(
    manifest.models
      .filter((m) => m.type === 'sap.ui.model.resource.ResourceModel')
      .map((m) => m.name),
  )
  resourceModels.add('i18n')
  const mock = inferMockData(
    sources.filter((s) => ['view', 'fragment'].includes(classifySource(s.path))),
    { skipModels: resourceModels },
  )
  const mockModels = Object.keys(mock)

  put(
    'manifest.json',
    'json',
    JSON.stringify(sanitizeManifest(manifestJson, mockModels), null, '\t'),
  )
  put('Component.js', 'js', componentSource(appId, mock))

  // controllers
  const routesByName = new Map(inventory.routes.map((r) => [r.name, r]))
  const controllerInfo = new Map(inventory.controllers.map((c) => [c.controllerName, c]))
  const sourceByName = new Map()
  for (const s of sources)
    if (classifySource(s.path) === 'controller') {
      const ctrl = inventory.controllers.find((c) => c.path === s.path)
      if (ctrl) sourceByName.set(ctrl.controllerName, s)
    }
  const fragmentFiles = new Map(
    sources.filter((s) => classifySource(s.path) === 'fragment').map((s) => [s.path, s]),
  )

  const names = new Set(inventory.views.map((v) => v.controllerName).filter(Boolean))
  for (const n of sourceByName.keys()) names.add(n)
  let stubbed = 0
  for (const name of names) {
    if (!name.startsWith(`${appId}.`)) {
      notes.push(`Controller ${name} is outside the app namespace and was left out.`)
      continue
    }
    const path = name.slice(appId.length + 1).replace(/\./g, '/') + '.controller.js'
    const real = sourceByName.get(name)
    if (mode === 'real' && real && /\.js$/i.test(real.path)) {
      put(path, 'js', real.content)
      continue
    }
    if (mode === 'real' && real)
      notes.push(
        `${real.path} is TypeScript and cannot run in the browser - a stub is used instead.`,
      )

    const ctrl = controllerInfo.get(name)
    const handlers = new Set()
    const hostedViews = inventory.views.filter((v) => v.controllerName === name)
    const addFrom = (xml) => {
      try {
        for (const c of parseXmlView(xml).controls)
          for (const h of Object.values(c.handlers)) if (!h.includes('.')) handlers.add(h)
      } catch {
        /* a broken view is reported when it loads */
      }
    }
    for (const v of hostedViews) addFrom(sources.find((s) => s.path === v.path).content)
    const hostedNames = new Set(hostedViews.map((v) => v.viewName))
    for (const f of inventory.fragments) {
      const hosted =
        f.hosts.some((h) => hostedNames.has(h.viewName)) ||
        (ctrl?.fragments ?? []).some((x) => x.name === f.fragmentName)
      const src = fragmentFiles.get(f.path)
      if (hosted && src) addFrom(src.content)
    }

    const actions = {}
    for (const h of handlers) {
      const nav = ctrl?.navigations.find((n) => n.method === h && n.route && !n.dynamic)
      const frag = ctrl?.fragments.find((f) => f.method === h)
      if (nav) {
        const params = {}
        for (const p of routesByName.get(nav.route)?.params ?? [])
          params[p] = nav.argValues?.[p] ?? '1'
        actions[h] = { navTo: { route: nav.route, params } }
      } else if (frag) {
        actions[h] = {
          fragment: {
            name: frag.name,
            id: frag.idMode === 'custom' ? frag.idPrefix : frag.idMode === 'view' ? 'view' : null,
          },
        }
      } else if (CLOSING.test(h)) {
        actions[h] = { close: true }
      } else {
        actions[h] = {}
      }
    }
    put(path, 'js', stubSource(name, actions))
    stubbed++
  }

  return {
    appId,
    files,
    info: {
      appId,
      controllers: mode,
      stubbedControllers: stubbed,
      rootView: manifest.rootView?.viewName ?? null,
      views: inventory.views.map((v) => ({ viewName: v.viewName, path: v.path })),
      routes: manifest.routes.map((r) => ({ name: r.name, pattern: r.pattern, params: r.params })),
      mockModels,
      warnings: inventory.warnings.map((w) => w.message),
      notes,
    },
  }
}
