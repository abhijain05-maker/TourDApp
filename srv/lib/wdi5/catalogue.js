// What an existing wdi5 project already has: its config, its specs, the helpers and page objects that drive controls
// (with the control and action each function uses), the selectors it defines, and how its code is written. Nothing is
// executed - the files are only parsed (acorn). The generator reuses what it finds here instead of writing a second copy.
import * as acorn from 'acorn'

const CONFIG = /(^|\/)wdio[\w.-]*\.conf\.(c|m)?js$/
/** Journeys TourD wrote earlier: they are generated from a plan, not helpers to build on. */
const GENERATED = /Generated by TourD from a recording/
const SPEC = /\.(test|spec)\.(c|m)?js$/
const SKIP_DIRS = /(^|\/)(node_modules|dist|build|coverage)\//
/** The app's own code (controllers, views) is not part of the tests; its test folder is. */
const isAppCode = (p) => /(^|\/)webapp\//.test(p) && !/(^|\/)webapp\/test\//.test(p)
const dirOf = (p) => p.slice(0, Math.max(0, p.lastIndexOf('/')))

function parse(text) {
  const base = {
    ecmaVersion: 'latest',
    allowReturnOutsideFunction: true,
    allowAwaitOutsideFunction: true,
    locations: false,
  }
  try {
    return { ast: acorn.parse(text, { ...base, sourceType: 'script' }), esm: false }
  } catch {
    try {
      return { ast: acorn.parse(text, { ...base, sourceType: 'module' }), esm: true }
    } catch {
      return null
    }
  }
}

/** The value of a literal-ish expression (objects, arrays, strings, numbers, booleans, null); undefined when it is not one. */
function literalValue(node) {
  if (!node) return undefined
  if (node.type === 'Literal') return node.regex ? undefined : node.value
  if (node.type === 'TemplateLiteral' && node.expressions.length === 0)
    return node.quasis[0].value.cooked
  if (node.type === 'ArrayExpression') {
    const items = node.elements.map(literalValue)
    return items.some((v) => v === undefined) ? undefined : items
  }
  if (node.type === 'UnaryExpression' && node.operator === '-' && node.argument.type === 'Literal')
    return -node.argument.value
  if (node.type === 'ObjectExpression') {
    const out = {}
    for (const p of node.properties) {
      if (p.type !== 'Property' || p.computed) return undefined
      const key = p.key.type === 'Identifier' ? p.key.name : p.key.value
      const v = literalValue(p.value)
      if (v === undefined) return undefined
      out[key] = v
    }
    return out
  }
  return undefined
}

const keyOf = (n) =>
  n.type === 'Identifier' ? n.name : n.type === 'Literal' ? String(n.value) : null

function docBefore(text, node) {
  const before = text.slice(0, node.start).trimEnd()
  if (!before.endsWith('*/')) return null
  const open = before.lastIndexOf('/**')
  if (open < 0) return null
  return (
    before
      .slice(open + 3, -2)
      .split('\n')
      .map((l) => l.replace(/^\s*\*\s?/, '').trim())
      .filter((l) => l && !l.startsWith('@'))
      .join(' ')
      .trim() || null
  )
}

/** Visit every node below `node` (a plain walk: acorn-walk would need the ancestors option for what we do). */
function visit(node, fn) {
  if (!node || typeof node.type !== 'string') return
  if (fn(node) === false) return
  for (const k of Object.keys(node)) {
    const v = node[k]
    if (Array.isArray(v)) v.forEach((c) => visit(c, fn))
    else if (v && typeof v.type === 'string') visit(v, fn)
  }
}

/** The controls a function drives: [{ selector, action, valueParam }]. `resolve` turns an expression into a selector. */
function usesIn(fn, resolve, text) {
  const params = fn.params.map((p) =>
    p.type === 'Identifier'
      ? p.name
      : p.type === 'AssignmentPattern' && p.left.type === 'Identifier'
        ? p.left.name
        : null,
  )
  const uses = []
  const vars = new Map() // variable -> selector, for `const c = await browser.asControl(sel)`
  const asControlOf = (node) => {
    let n = node
    while (n && (n.type === 'AwaitExpression' || n.type === 'ParenthesizedExpression'))
      n = n.argument ?? n.expression
    if (
      n?.type === 'CallExpression' &&
      n.callee.type === 'MemberExpression' &&
      n.callee.property.name === 'asControl'
    )
      return resolve(n.arguments[0])
    return undefined
  }
  visit(fn.body, (node) => {
    if (node.type === 'VariableDeclarator' && node.id.type === 'Identifier') {
      const s = asControlOf(node.init)
      if (s) vars.set(node.id.name, s)
    }
    if (node.type !== 'CallExpression' || node.callee.type !== 'MemberExpression') return
    const action = node.callee.property.name
    let target = node.callee.object
    let selector = asControlOf(target)
    if (!selector && target.type === 'Identifier') selector = vars.get(target.name)
    if (!selector && target.type === 'AwaitExpression') selector = asControlOf(target)
    if (!selector) return
    const arg = node.arguments[0]
    const valueParam = arg?.type === 'Identifier' ? params.indexOf(arg.name) : -1
    uses.push({ selector, action, valueParam: valueParam >= 0 ? valueParam : null })
  })
  void text
  return uses
}

/**
 * How a caller gets at an export. kind: "named" (import { importName }), "module" (the whole CommonJS module),
 * "default" (ES default import). object: the export is an object/instance whose members are called (binding.method()),
 * not a function that is called itself. hint: a name to build the local binding from.
 */
const access = (kind, rest = {}) => ({ kind, object: false, ...rest })

/** Exported functions and methods of one file, with what they do. */
function describeFile(path, text, parsed) {
  const { ast, esm } = parsed
  const consts = new Map() // top-level name -> node
  const fns = new Map() // top-level function name -> { node, doc }
  const classes = new Map()
  for (const n of ast.body) {
    const decl =
      n.type === 'ExportNamedDeclaration' || n.type === 'ExportDefaultDeclaration'
        ? n.declaration
        : n
    if (!decl) continue
    if (decl.type === 'FunctionDeclaration' && decl.id)
      fns.set(decl.id.name, { node: decl, doc: docBefore(text, n) })
    if (decl.type === 'ClassDeclaration' && decl.id)
      classes.set(decl.id.name, { node: decl, doc: docBefore(text, n) })
    if (decl.type === 'VariableDeclaration')
      for (const d of decl.declarations) {
        if (d.id.type !== 'Identifier' || !d.init) continue
        consts.set(d.id.name, d.init)
        if (d.init.type === 'ArrowFunctionExpression' || d.init.type === 'FunctionExpression')
          fns.set(d.id.name, { node: d.init, doc: docBefore(text, n) })
      }
  }

  const membersOfObject = (obj) => {
    const m = new Map()
    for (const p of obj.properties)
      if (p.type === 'Property' && !p.computed) m.set(keyOf(p.key), p.value)
    return m
  }
  const membersOfClass = (cls) => {
    const m = new Map()
    for (const e of cls.body.body) {
      if (e.type === 'PropertyDefinition' && e.value && !e.computed) m.set(keyOf(e.key), e.value)
      if (e.type === 'MethodDefinition' && e.kind === 'get' && !e.computed) {
        const ret = e.value.body.body.find((s) => s.type === 'ReturnStatement')
        if (ret?.argument) m.set(keyOf(e.key), ret.argument)
      }
    }
    return m
  }
  const resolveIn = (scope) => (expr) => {
    if (!expr) return undefined
    const direct = literalValue(expr)
    if (direct && typeof direct === 'object' && direct.selector) return direct.selector
    if (expr.type === 'Identifier' && consts.has(expr.name))
      return resolveIn(scope)(consts.get(expr.name))
    if (expr.type === 'MemberExpression' && !expr.computed) {
      const prop = expr.property.name
      // locators.createBtn / this.createButton / Page.createButton
      const found =
        scope.members.get(prop) ??
        (expr.object.type === 'Identifier' &&
        consts.get(expr.object.name)?.type === 'ObjectExpression'
          ? membersOfObject(consts.get(expr.object.name)).get(prop)
          : undefined)
      if (found) return resolveIn(scope)(found)
    }
    return undefined
  }

  const exported = []
  const selectors = []
  const noScope = { members: new Map() }
  const paramsOf = (node) =>
    node.params.map((p) =>
      p.type === 'Identifier'
        ? p.name
        : p.type === 'AssignmentPattern' && p.left.type === 'Identifier'
          ? p.left.name
          : '…',
    )
  const fnEntry = (name, node, doc, scope, acc, owner = null) => ({
    name,
    kind: 'function',
    params: paramsOf(node),
    async: !!node.async,
    doc,
    access: acc,
    owner,
    uses: usesIn(node, resolveIn(scope), text),
    // pressing Enter after typing: what a search needs
    submits: /\.keys\s*\(/.test(text.slice(node.start, node.end)),
  })
  const isFn = (v) =>
    v &&
    (v.type === 'FunctionExpression' ||
      v.type === 'ArrowFunctionExpression' ||
      v.type === 'FunctionDeclaration')

  /** A class whose instance (or whose statics) is what the module exports. */
  const addClass = (className, acc, staticOnly) => {
    const c = classes.get(className)
    if (!c) return
    const scope = { members: membersOfClass(c.node) }
    if (!staticOnly)
      for (const [member, value] of scope.members) {
        const sel = resolveIn(scope)(value)
        if (sel) selectors.push({ name: member, selector: sel, access: acc })
      }
    for (const e of c.node.body.body)
      if (
        e.type === 'MethodDefinition' &&
        e.kind === 'method' &&
        !e.computed &&
        keyOf(e.key) !== 'constructor' &&
        !!e.static === staticOnly
      )
        exported.push(fnEntry(keyOf(e.key), e.value, docBefore(text, e), scope, acc, className))
  }
  /** An object literal that is exported: its functions and its selectors. */
  const addObject = (obj, acc, asObject) => {
    const scope = { members: membersOfObject(obj) }
    for (const p of obj.properties) {
      if (p.type !== 'Property' || p.computed) continue
      const key = keyOf(p.key)
      const value =
        p.value.type === 'Identifier'
          ? (fns.get(p.value.name)?.node ?? consts.get(p.value.name))
          : p.value
      const entryAccess = asObject ? acc : access('named', { importName: key })
      if (isFn(value)) exported.push(fnEntry(key, value, docBefore(text, p), scope, entryAccess))
      else {
        const sel = resolveIn(scope)(p.value)
        if (sel)
          selectors.push({
            name: key,
            selector: sel,
            access: asObject ? { ...acc, member: key } : entryAccess,
          })
      }
    }
  }
  const named = (name) => access('named', { importName: name })

  for (const n of ast.body) {
    // ---- CommonJS ----
    if (n.type === 'ExpressionStatement' && n.expression.type === 'AssignmentExpression') {
      const left = n.expression.left
      const right = n.expression.right
      const lt = text.slice(left.start, left.end)
      const member = /^(?:module\.)?exports\.(\w+)$/.exec(lt)?.[1]
      if (lt === 'module.exports') {
        if (right.type === 'ObjectExpression') addObject(right, null, false)
        else if (right.type === 'NewExpression' && right.callee.type === 'Identifier')
          addClass(
            right.callee.name,
            access('module', { object: true, hint: right.callee.name }),
            false,
          )
        else if (right.type === 'Identifier' && classes.has(right.name))
          addClass(right.name, access('module', { object: true, hint: right.name }), true)
        else if (right.type === 'Identifier' && fns.has(right.name))
          exported.push(
            fnEntry(
              right.name,
              fns.get(right.name).node,
              fns.get(right.name).doc,
              noScope,
              access('module', { hint: right.name }),
            ),
          )
      } else if (member) {
        if (isFn(right))
          exported.push(fnEntry(member, right, docBefore(text, n), noScope, named(member)))
        else if (right.type === 'Identifier' && fns.has(right.name))
          exported.push(
            fnEntry(
              member,
              fns.get(right.name).node,
              fns.get(right.name).doc,
              noScope,
              named(member),
            ),
          )
        else {
          const sel = resolveIn(noScope)(right)
          if (sel) selectors.push({ name: member, selector: sel, access: named(member) })
        }
      }
    }
    // ---- ES modules ----
    if (n.type === 'ExportNamedDeclaration') {
      const d = n.declaration
      if (d?.type === 'FunctionDeclaration')
        exported.push(fnEntry(d.id.name, d, docBefore(text, n), noScope, named(d.id.name)))
      if (d?.type === 'ClassDeclaration')
        addClass(d.id.name, access('named', { importName: d.id.name, object: true }), true)
      if (d?.type === 'VariableDeclaration')
        for (const v of d.declarations) {
          if (v.id.type !== 'Identifier') continue
          if (isFn(v.init))
            exported.push(fnEntry(v.id.name, v.init, docBefore(text, n), noScope, named(v.id.name)))
          else if (v.init?.type === 'NewExpression' && v.init.callee.type === 'Identifier')
            addClass(
              v.init.callee.name,
              access('named', { importName: v.id.name, object: true }),
              false,
            )
          else {
            const sel = resolveIn(noScope)(v.init)
            if (sel) selectors.push({ name: v.id.name, selector: sel, access: named(v.id.name) })
          }
        }
      for (const s of n.specifiers ?? []) {
        const local = s.local.name
        if (fns.has(local))
          exported.push(
            fnEntry(
              s.exported.name,
              fns.get(local).node,
              fns.get(local).doc,
              noScope,
              named(s.exported.name),
            ),
          )
      }
    }
    if (n.type === 'ExportDefaultDeclaration') {
      const d = n.declaration
      const hint = d.id?.name ?? path
      if (d.type === 'ClassDeclaration')
        addClass(d.id?.name, access('default', { object: true, hint }), true)
      else if (d.type === 'ObjectExpression')
        addObject(d, access('default', { object: true, hint }), true)
      else if (d.type === 'NewExpression' && d.callee.type === 'Identifier')
        addClass(d.callee.name, access('default', { object: true, hint: d.callee.name }), false)
      else if (d.type === 'Identifier' && classes.has(d.name))
        addClass(d.name, access('default', { object: true, hint: d.name }), true)
      else if (d.type === 'Identifier' && fns.has(d.name))
        exported.push(
          fnEntry(
            d.name,
            fns.get(d.name).node,
            fns.get(d.name).doc,
            noScope,
            access('default', { hint: d.name }),
          ),
        )
      else if (isFn(d))
        exported.push(
          fnEntry(
            d.id?.name ?? 'default',
            d,
            docBefore(text, n),
            noScope,
            access('default', { hint: d.id?.name ?? path }),
          ),
        )
    }
  }
  return { path, esm, exports: exported, selectors }
}

/** The indentation, quotes and semicolons the project's own code uses (judged on the files given). */
export function detectStyle(texts) {
  const text = texts.join('\n')
  const lines = text.split('\n')
  const tabs = lines.filter((l) => /^\t+\S/.test(l)).length
  const spaces = lines.filter((l) => /^ +\S/.test(l))
  const widths = spaces.map((l) => /^ */.exec(l)[0].length).filter((w) => w > 0)
  const unit = widths.length ? Math.min(...widths.filter((w) => w >= 2)) || 2 : 4
  const single = (text.match(/'[^'\n]*'/g) ?? []).length
  const double = (text.match(/"[^"\n]*"/g) ?? []).length
  const stmts = lines.filter((l) =>
    /^\s*(const|let|var|await|return|expect|browser)\b.*[\w)\]'"`}]$/.test(l.trimEnd()),
  )
  const semis = lines.filter((l) =>
    /^\s*(const|let|var|await|return|expect|browser)\b.*;\s*$/.test(l),
  ).length
  return {
    useTabs: tabs > spaces.length,
    tabWidth: Math.min(Math.max(unit, 2), 8),
    singleQuote: single > double,
    semi: stmts.length + semis === 0 ? false : semis >= stmts.length,
  }
}

const globToRegExp = (glob) => {
  const re = glob
    .replace(/^\.\//, '')
    .replace(/[.+^${}()|[\]\\]/g, '\\$&')
    .replace(/\*\*\//g, '(?:.*/)?')
    .replace(/\*\*/g, '.*')
    .replace(/\*/g, '[^/]*')
  return new RegExp(`^${re}$`)
}

/** Does one of the globs of `specs` (relative to the config's folder) match this file? */
export function specGlobMatches(globs, configDir, path) {
  const rel =
    configDir && path.startsWith(`${configDir}/`) ? path.slice(configDir.length + 1) : path
  return globs.some((g) => typeof g === 'string' && globToRegExp(g).test(rel))
}

function describeConfig(path, text) {
  const parsed = parse(text)
  const info = {
    path,
    text,
    esm: !!parsed?.esm,
    specs: [],
    framework: null,
    services: [],
    baseUrl: null,
    readable: !!parsed,
    hasAuth: /wdi5:authentication/.test(text),
  }
  if (!parsed) return info
  visit(parsed.ast, (node) => {
    if (node.type !== 'Property' || node.computed) return
    const k = keyOf(node.key)
    if (k === 'specs' && node.value.type === 'ArrayExpression') {
      const v = literalValue(node.value)
      // nested arrays (grouped specs) and non-literal entries: leave the list as unknown rather than guess
      if (v) info.specs = v.flat().filter((x) => typeof x === 'string')
      info.specsNode = { start: node.value.start, end: node.value.end, literal: !!v }
    }
    if (k === 'framework') info.framework = literalValue(node.value) ?? null
    if (k === 'services' && node.value.type === 'ArrayExpression') {
      info.services = node.value.elements
        .map((e) =>
          e?.type === 'Literal'
            ? e.value
            : e?.type === 'ArrayExpression' && e.elements[0]?.type === 'Literal'
              ? e.elements[0].value
              : null,
        )
        .filter(Boolean)
      info.servicesNode = { start: node.value.start, end: node.value.end }
    }
    if (k === 'baseUrl')
      info.baseUrl =
        literalValue(node.value) ??
        (node.value.type === 'LogicalExpression' ? (literalValue(node.value.right) ?? null) : null)
  })
  return info
}

/**
 * @param {{path: string, content: string}[]} files the project's text files
 */
export function buildCatalogue(files) {
  const js = files.filter(
    (f) => /\.(c|m)?js$/.test(f.path) && !SKIP_DIRS.test(f.path) && !isAppCode(f.path),
  )
  const configs = js.filter(
    (f) =>
      CONFIG.test(f.path) &&
      /(exports\.config|export\s+const\s+config|defineConfig)/.test(f.content),
  )
  // the config closest to the root is the project's
  const config = configs.sort((a, b) => a.path.split('/').length - b.path.split('/').length)[0]
  const configInfo = config ? describeConfig(config.path, config.content) : null

  const specs = js.filter((f) => SPEC.test(f.path) && /\b(describe|it)\s*\(/.test(f.content))
  const specSet = new Set(specs.map((s) => s.path))
  const helperCandidates = js.filter(
    (f) =>
      !specSet.has(f.path) &&
      !CONFIG.test(f.path) &&
      !GENERATED.test(f.content) &&
      /(asControl|asObject|wdio-ui5-service|wdi5|browser\.)/.test(f.content),
  )
  const helpers = []
  for (const f of helperCandidates) {
    const parsed = parse(f.content)
    if (!parsed) continue
    const d = describeFile(f.path, f.content, parsed)
    if (d.exports.length || d.selectors.length) helpers.push(d)
  }

  const pkg = files
    .filter((f) => /(^|\/)package\.json$/.test(f.path) && !SKIP_DIRS.test(f.path))
    .sort((a, b) => a.path.split('/').length - b.path.split('/').length)[0]
  let deps = {}
  try {
    deps = pkg
      ? { ...JSON.parse(pkg.content).dependencies, ...JSON.parse(pkg.content).devDependencies }
      : {}
  } catch {
    /* an unreadable package.json says nothing */
  }
  const dirs = specs.map((s) => dirOf(s.path))
  const specDir = dirs.length
    ? [...new Set(dirs)].sort(
        (a, b) => dirs.filter((d) => d === b).length - dirs.filter((d) => d === a).length,
      )[0]
    : null
  const styleFiles = [
    ...specs,
    ...helperCandidates.filter((h) => helpers.some((x) => x.path === h.path)),
  ].slice(0, 8)
  const hasTs = files.some(
    (f) => /\.(test|spec)\.ts$/.test(f.path) || /(^|\/)wdio[\w.-]*\.conf\.ts$/.test(f.path),
  )
  const wdi5 = !!(deps['wdio-ui5-service'] || deps.wdi5 || configInfo?.services.includes('ui5'))
  return {
    wdi5,
    typescript: hasTs && !configInfo,
    config: configInfo,
    configDir: configInfo ? dirOf(configInfo.path) : null,
    specs: specs.map((s) => ({ path: s.path })),
    specDir,
    helpers,
    selectors: helpers.flatMap((h) => h.selectors.map((s) => ({ ...s, path: h.path }))),
    esm: configInfo ? configInfo.esm : specs.length ? !!parse(specs[0].content)?.esm : false,
    style: styleFiles.length ? detectStyle(styleFiles.map((f) => f.content)) : null,
    dependencies: deps,
  }
}

const sameSelector = (a, b) => {
  if (!a || !b) return false
  if (a.id && b.id) return a.id === b.id && (a.viewName ?? null) === (b.viewName ?? null)
  return JSON.stringify(a) === JSON.stringify(b)
}

/**
 * Finds the helper that already does what a step does: the same control, the same action.
 * @returns {{file: string, name: string, owner: string|null, via: string|null, params: string[], valueParam: number|null}|null}
 */
export function findReusable(catalogue, selectors, action) {
  const want =
    action === 'enterText' || action === 'search'
      ? 'enterText'
      : action === 'select'
        ? null
        : 'press'
  if (!want) return null
  let best = null
  for (const h of catalogue.helpers)
    for (const e of h.exports) {
      // a helper that does one thing: exactly one control, and that action
      if (e.uses.length !== 1) continue
      const u = e.uses[0]
      if (u.action !== want || !selectors.some((s) => sameSelector(u.selector, s))) continue
      if (want === 'press' && e.params.length > 0) continue
      if (want === 'enterText' && u.valueParam === null) continue
      if (action === 'search' && !e.submits) continue // a search is typing and then Enter: the helper must do both
      const found = {
        file: h.path,
        name: e.name,
        owner: e.owner ?? null,
        access: e.access,
        params: e.params,
        valueParam: u.valueParam,
      }
      if (!best || found.params.length < best.params.length) best = found
    }
  return best
}

/** An exported selector of the project that is this control. */
export function findSelector(catalogue, selectors) {
  const hit = catalogue.selectors.find((c) => selectors.some((s) => sameSelector(c.selector, s)))
  return hit ? { file: hit.path, name: hit.name, access: hit.access } : null
}

/** Helpers that set up a run: log in, open the app. */
export function findSetup(catalogue) {
  const out = { login: null, open: null }
  for (const h of catalogue.helpers)
    for (const e of h.exports) {
      if (e.params.length) continue
      const entry = {
        file: h.path,
        name: e.name,
        owner: e.owner ?? null,
        access: e.access,
        async: e.async,
      }
      if (!out.login && /^(login|logIn|signIn|logon)\w*$/i.test(e.name)) out.login = entry
      else if (
        !out.open &&
        /^(open|launch|start|navigate|goTo|go)\w*(app|page|home|start|launchpad)?$/i.test(e.name) &&
        e.uses.length === 0
      )
        out.open = entry
    }
  return out
}
