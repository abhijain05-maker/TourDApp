const IND = '    '

/** A JavaScript literal: double-quoted strings, bare keys where possible, multi-line when it is not short. */
export function literal(value, depth = 0) {
  const pad = IND.repeat(depth + 1)
  const end = IND.repeat(depth)
  if (value === null || typeof value !== 'object') return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map((v) => literal(v, depth)).join(', ')}]`
  const entries = Object.entries(value)
  if (!entries.length) return '{}'
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))
  const flat = `{ ${entries.map(([k, v]) => `${key(k)}: ${literal(v, depth + 1)}`).join(', ')} }`
  if (flat.length <= 90 && !flat.includes('\n')) return flat
  return `{\n${entries.map(([k, v]) => `${pad}${key(k)}: ${literal(v, depth + 1)}`).join(',\n')}\n${end}}`
}

const q = (s) => JSON.stringify(String(s))
/** Text that goes into a comment: one line, and it cannot end the comment. */
const c = (s) =>
  String(s ?? '')
    .replace(/\s+/g, ' ')
    .replaceAll('*/', '* /')
    .trim()

