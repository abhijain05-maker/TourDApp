const dirname = (p) => p.slice(0, Math.max(0, p.lastIndexOf('/')))

/** "../helpers/ui5" from a file to another one (both relative to the same root, forward slashes). */
export function relativeSpecifier(fromFile, toFile, { esm }) {
  const from = dirname(fromFile).split('/').filter(Boolean)
  const to = toFile.split('/')
  let i = 0
  while (i < from.length && i < to.length - 1 && from[i] === to[i]) i++
  const up = from.slice(i).map(() => '..')
  const spec = [...(up.length ? up : ['.']), ...to.slice(i)].join('/')
  return esm ? spec : spec.replace(/\.(c|m)?js$/, '')
}

/** The require / import lines of one generated file, with names that cannot clash. */
export class Imports {
  constructor({ from, esm }) {
    this.from = from
    this.esm = esm
    this.byFile = new Map()
    this.taken = new Set()
    this.externals = []
  }

  unique(hint) {
    const base = identifier(
      String(hint)
        .replace(/^.*\//, '')
        .replace(/\.(c|m)?js$/, ''),
      'helper',
    )
    let name = base
    for (let n = 2; this.taken.has(name); n++) name = `${base}${n}`
    this.taken.add(name)
    return name
  }

  entry(file) {
    if (!this.byFile.has(file))
      this.byFile.set(file, {
        named: new Map(),
        whole: null,
        spec: relativeSpecifier(this.from, file, { esm: this.esm }),
      })
    return this.byFile.get(file)
  }

  /** `import { importName }`: the local name to use. */
  named(file, importName) {
    const e = this.entry(file)
    if (!e.named.has(importName)) {
      let local = importName
      if (this.taken.has(local)) local = this.unique(importName)
      else this.taken.add(local)
      e.named.set(importName, local)
    }
    return e.named.get(importName)
  }

  /** The whole module (CommonJS `require`) or the default export (ES `import x from`). */
  whole(file, hint) {
    const e = this.entry(file)
    e.whole ??= this.unique(hint ?? file)
    return e.whole
  }

  /** A package: `const { a } = require("pkg")`. */
  external(pkg, names) {
    for (const n of names) this.taken.add(n)
    this.externals.push({ pkg, names })
  }

  lines() {
    const out = []
    for (const { pkg, names } of this.externals)
      out.push(
        this.esm
          ? `import { ${names.join(', ')} } from ${q(pkg)}`
          : `const { ${names.join(', ')} } = require(${q(pkg)})`,
      )
    for (const [, e] of this.byFile) {
      const names = [...e.named].map(([imported, local]) =>
        imported === local
          ? imported
          : this.esm
            ? `${imported} as ${local}`
            : `${imported}: ${local}`,
      )
      if (e.whole && this.esm)
        out.push(
          `import ${e.whole}${names.length ? `, { ${names.join(', ')} }` : ''} from ${q(e.spec)}`,
        )
      else {
        if (e.whole) out.push(`const ${e.whole} = require(${q(e.spec)})`)
        if (names.length)
          out.push(
            this.esm
              ? `import { ${names.join(', ')} } from ${q(e.spec)}`
              : `const { ${names.join(', ')} } = require(${q(e.spec)})`,
          )
      }
    }
    return out
  }
}

/** The expression that reaches an export of a project file: `login`, `mainPage.startNewOrder`. */
function reach(imports, helper, member = helper.name) {
  const a = helper.access
  const base =
    a.kind === 'named'
      ? imports.named(helper.file, a.importName ?? helper.name)
      : imports.whole(helper.file, a.hint ?? helper.file)
  return a.object ? `${base}.${member}` : base
}

// ---- the journey and the spec ----------------------------------------------------------------------------------

/** Unique JavaScript names for the steps that act. */
function stepNames(steps) {
  const taken = new Set()
  const names = new Map()
  for (const s of steps) {
    if (s.kind === 'assert' || !s.enabled) continue
    const base = identifier(s.title, `step${names.size + 1}`)
    let name = base
    for (let n = 2; taken.has(name); n++) name = `${base}${n}`
    taken.add(name)
    names.set(s.id, name)
  }
  return names
}

const call = (step, locator, helpers) => {
  const l = `locators.${locator}`
  if (step.kind === 'press') return `await browser.asControl(${l}).press()`
  if (step.kind === 'select') return `await ${helpers.choose}(${l}, ${q(step.choice ?? '')})`
  const opts = step.submit || step.kind === 'search' ? ', { submit: true }' : ''
  return `await ${helpers.typeInto}(${l}, ${q(step.value ?? '')}${opts})`
}

/** What a helper of the project is called with, for a step. */
function reuseCall(imports, helper, step) {
  const callee = reach(imports, helper)
  if (step.kind === 'press') return `await ${callee}()`
  const args = helper.params.map((_, i) =>
    i === helper.valueParam ? q(step.value ?? '') : 'undefined',
  )
  while (args.length && args.at(-1) === 'undefined') args.pop()
  return `await ${callee}(${args.join(', ')})`
}

function assertion(step, locators) {
  const a = step.assertion
  const l = step.locator && locators[step.locator] ? `locators.${step.locator}` : null
  switch (a.type) {
    case 'url':
      return a.expected
        ? `await expect(browser).toHaveUrl(expect.stringContaining(${q(`#/${a.expected.replace(/^#?\/?/, '')}`)}))`
        : 'await expect(browser).toHaveUrl(expect.stringMatching(/^[^#]*#?\\/?$/))'
    case 'value':
      return l && `expect(await browser.asControl(${l}).getValue()).toBe(${q(a.expected ?? '')})`
    case 'selectedKey':
      return (
        l && `expect(await browser.asControl(${l}).getSelectedKey()).toBe(${q(a.expected ?? '')})`
      )
    case 'visible':
      return l && `expect(await browser.asControl(${l}).getVisible()).toBe(true)`
    case 'text':
      return l && `expect(await browser.asControl(${l}).getText()).toBe(${q(a.expected ?? '')})`
    default:
      return null
  }
}

const literalSelector = (l) => literal({ selector: l.selector }, 1)

/**
 * @param {object} plan
 * @param {{esm?: boolean, journeyFile?: string, helpersFile?: string,
 *          reuse?: {steps: Map<string, object>, locators: Map<string, object>, setup: {login?: object, open?: object}}}} [ctx]
 *   reuse: what the project already has (see reuse.js); the journey calls it instead of doing it again
 */
export function renderJourney(plan, ctx = {}) {
  const esm = !!ctx.esm
  const journeyFile = ctx.journeyFile ?? 'journeys/x.journey.js'
  const reuse = ctx.reuse ?? { steps: new Map(), locators: new Map(), setup: {} }
  const names = stepNames(plan.steps)
  const acting = plan.steps.filter((s) => names.has(s.id) && s.kind !== 'open' && s.locator)
  const imports = new Imports({ from: journeyFile, esm })
  const open = plan.steps.find((s) => s.kind === 'open' && s.enabled)
  const hash = open?.hash
    ? open.hash.startsWith('#')
      ? open.hash
      : `#/${open.hash.replace(/^\//, '')}`
    : null
  if (hash) imports.external('wdio-ui5-service', ['wdi5'])

  const used = new Set(plan.steps.filter((s) => s.enabled && s.locator).map((s) => s.locator))
  const locators = Object.entries(plan.locators)
    .filter(([key]) => used.has(key))
    .map(([key, l]) => {
      const shared = reuse.locators.get(key)
      const value = shared
        ? reach(imports, shared, shared.access.member ?? shared.name)
        : literalSelector(l)
      return `${IND}${/^[A-Za-z_$][\w$]*$/.test(key) ? key : q(key)}: ${value}`
    })
    .join(',\n')

  // our own helpers only for the steps the project has nothing for
  const needs = new Set(
    acting
      .filter((s) => !reuse.steps.has(s.id))
      .map((s) =>
        s.kind === 'select'
          ? 'choose'
          : ['enterText', 'search'].includes(s.kind)
            ? 'typeInto'
            : null,
      )
      .filter(Boolean),
  )
  const helpers = {}
  for (const n of [...needs].sort())
    helpers[n] = imports.named(ctx.helpersFile ?? 'helpers/ui5.js', n)

  const functions = acting.map((s) => {
    const shared = reuse.steps.get(s.id)
    const body = shared ? reuseCall(imports, shared, s) : call(s, s.locator, helpers)
    return `/** ${c(s.title)}${shared ? ` (uses ${c(shared.name)} of the project)` : ''} */\nasync function ${names.get(s.id)}() {\n${IND}${body}\n}`
  })
  const setupLines = [reuse.setup.login, reuse.setup.open]
    .filter(Boolean)
    .map((h) => `${IND}await ${reach(imports, h)}()`)
  if (hash) setupLines.push(`${IND}await wdi5.goTo(${q(hash)})`)
  const body = setupLines.length
    ? setupLines.join('\n')
    : `${IND}// nothing to do: wdi5 has opened the app at baseUrl`
  const exported = ['locators', 'openApp', ...acting.map((s) => names.get(s.id))]
  return `// The journey "${c(plan.name)}": the controls it uses and one function per step.
// Generated by TourD from a recording. Change it freely; the specs call these functions.
${imports.lines().join('\n')}

// How wdi5 finds each control (see https://ui5-community.github.io/wdi5/#/locators)
const locators = {
${locators}
}

/** The start of every spec: wdi5 has opened the app at baseUrl already. */
async function openApp() {
${body}
}

${functions.join('\n\n')}

${esm ? `export { ${exported.join(', ')} }` : `module.exports = { ${exported.join(', ')} }`}
`
}

/**
 * @param {object} plan
 * @param {string} journeyImport an import specifier ("../journeys/x.journey"), or just the file name
 * @param {{esm?: boolean}} [ctx]
 */
export function renderSpec(plan, journeyImport, ctx = {}) {
  const esm = !!ctx.esm
  const specifier = journeyImport.includes('/') ? journeyImport : `../journeys/${journeyImport}`
  const jasmine = plan.settings.framework === 'jasmine'
  const names = stepNames(plan.steps)
  const blocks = []
  let current = null
  for (const s of plan.steps) {
    if (s.kind === 'open') continue
    if (s.kind === 'assert') {
      if (!s.enabled) continue
      const line = assertion(s, plan.locators)
      if (!line) continue
      // a check that comes first (or after a step that is switched off) is a test of its own
      if (!current) {
        current = { title: s.title, lines: [] }
        blocks.push(current)
      }
      current.lines.push(`// ${c(s.title)}`, line)
      continue
    }
    if (!s.enabled) {
      current = null
      blocks.push({ skipped: true, title: s.title, note: s.note, lines: [] })
      continue
    }
    current = { title: s.title, lines: [`await journey.${names.get(s.id)}()`] }
    blocks.push(current)
  }
  const usesLocators = blocks.some((b) => b.lines.some((l) => l.includes('locators.')))
  const its = blocks
    .map((b) =>
      b.skipped
        ? `${IND}// ${c(b.note ?? 'left out')}\n${IND}xit(${q(b.title)}, async () => {})`
        : `${IND}it(${q(b.title)}, async () => {\n${b.lines.map((l) => `${IND}${IND}${l}`).join('\n')}\n${IND}})`,
    )
    .join('\n\n')
  return `// ${c(plan.name)}: generated by TourD from a recording. Run with: npx wdio run wdio.conf.js
${esm ? `import * as journey from ${q(specifier)}` : `const journey = require(${q(specifier)})`}
${usesLocators ? 'const { locators } = journey\n' : ''}
describe(${q(plan.name)}, () => {
${IND}${jasmine ? 'beforeAll' : 'before'}(async () => {
${IND}${IND}await journey.openApp()
${IND}})

${its}
})
`
}

