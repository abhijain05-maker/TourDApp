/**
 * @param {{plan: object, root: string}} args root: folder of the project root with a trailing slash ('' for the top)
 * @returns {{path: string, content: string, what: string, kind: 'config'|'package'|'support'|'journey'|'spec'|'docs'}[]}
 */
export function renderProject({ plan, root, packageJson, appId }) {
  const dir = `${root}${plan.settings.testDir.replace(/^\/+|\/+$/g, '')}`
  const name = slug(plan.name)
  const paths = {
    helpers: `${dir}/helpers/ui5.js`,
    journey: `${dir}/journeys/${name}.journey.js`,
    spec: `${dir}/specs/${name}.test.js`,
  }
  const files = [
    {
      path: `${root}wdio.conf.js`,
      kind: 'config',
      what: 'WebdriverIO and wdi5 configuration',
      content: renderConfig({
        settings: plan.settings,
        specGlob: `./${dir.slice(root.length)}/specs/**/*.test.js`,
      }),
    },
    {
      path: `${root}.env.example`,
      kind: 'support',
      what: 'The settings that belong in .env (address, login)',
      content: renderEnvExample(plan.settings),
    },
    {
      path: paths.helpers,
      kind: 'support',
      what: 'Shared helpers for the journeys',
      content: renderHelpers(false),
    },
    {
      path: paths.journey,
      kind: 'journey',
      what: 'The controls and the steps of the journey',
      content: renderJourney(plan),
    },
    {
      path: paths.spec,
      kind: 'spec',
      what: 'The test with its checks',
      content: renderSpec(plan, `${name}.journey`),
    },
    {
      path: `${dir}/README.md`,
      kind: 'docs',
      what: 'How to run the tests',
      content: README(plan, {
        ...paths,
        helpers: paths.helpers.slice(dir.length + 1),
        journey: paths.journey.slice(dir.length + 1),
        spec: paths.spec.slice(dir.length + 1),
      }),
    },
  ]
  const pkg = patchPackageJson(packageJson ?? null, {
    appId: appId ?? plan.app.id,
    framework: plan.settings.framework,
  })
  return { files, pkg: { path: `${root}package.json`, ...pkg } }
}
