function authBlock(settings) {
  const p = {
    basic: `provider: "BasicAuth"`,
    btp: `provider: "BTP"`,
    custom: `provider: "custom",
                usernameSelector: ${q(settings.authSelectors?.username ?? "input[id='username']")},
                passwordSelector: ${q(settings.authSelectors?.password ?? "input[id='password']")},
                submitSelector: ${q(settings.authSelectors?.submit ?? "button[type='submit']")}`,
  }[settings.auth]
  if (!p) return ''
  return `,
            // the user name and password come from the environment (wdi5_username, wdi5_password), never from here
            "wdi5:authentication": {
                ${p}
            }`
}

